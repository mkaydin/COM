#!/usr/bin/env node
/**
 * Vendor the three webfonts into com_website/fonts/ so the app renders the
 * same offline as it does online.
 *
 * Material Symbols is requested with `icon_names=` so Google returns a subset
 * containing only the ~75 icons this app uses. The full variable font is a
 * couple of megabytes; the subset is a few tens of kilobytes.
 *
 *   node desktop/fetch-fonts.js
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const REPO = path.join(__dirname, '..');
const WEB = path.join(REPO, 'com_website');
const FONT_DIR = path.join(WEB, 'fonts');

const FAMILIES = [
  {
    name: 'VT323',
    url: 'https://fonts.googleapis.com/css2?family=VT323&display=swap',
    slug: 'vt323',
  },
  {
    name: 'Be Vietnam Pro',
    url: 'https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@400;500;700;900&display=swap',
    slug: 'be-vietnam-pro',
  },
];

/** Every Material Symbols glyph the app can render.
 *
 *  Three sources, unioned, because any one of them alone is wrong:
 *
 *  * `/tmp/icons.json` — produced by `collect-icons.js`, which reads the
 *    rendered DOM. This is the only source that catches icons created from JS.
 *  * inline `<span class="material-symbols-outlined">name</span>` — catches
 *    icons behind interaction that never render on load.
 *  * NAV arrays like `['models.html', 'tune', 'Models']` and `icon:` object
 *    properties.
 *
 *  An earlier version used only the two regexes and shipped a subset without
 *  `tune`, so the sidebar rendered the literal word "TUNE".
 */
function collectIcons() {
  const icons = new Set();

  const harvested = process.argv.includes('--from-dom')
    ? '/tmp/icons.json'
    : null;
  if (harvested && fs.existsSync(harvested)) {
    for (const i of JSON.parse(fs.readFileSync(harvested, 'utf8'))) icons.add(i);
  }

  const patterns = [
    /material-symbols-outlined[^>]*>\s*([a-z0-9_]+)\s*</g,
    /\bicon:\s*'([a-z0-9_]+)'/g,
    /\.textContent\s*=\s*'([a-z0-9_]+)'/g,
    /\['[\w.]+\.html',\s*'([a-z0-9_]+)'\s*,/g,
  ];
  for (const f of fs.readdirSync(WEB).filter((x) => x.endsWith('.html'))) {
    const src = fs.readFileSync(path.join(WEB, f), 'utf8');
    for (const rx of patterns) for (const m of src.matchAll(rx)) icons.add(m[1]);
  }
  return [...icons].sort();
}

function curl(url, outFile) {
  execFileSync('curl', ['-fsSL', '--max-time', '90', '-A',
    'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 Chrome/120 Safari/537.36',
    url, '-o', outFile], { stdio: ['ignore', 'ignore', 'pipe'] });
}

/** Rewrite the remote @font-face URLs to local files. */
function localise(css, slug) {
  let n = 0;
  const out = css.replace(/url\((https:\/\/[^)]+)\)/g, (_m, url) => {
    n += 1;
    const file = path.basename(new URL(url).pathname);
    return `url(fonts/${slug}-${file})`;
  });
  return { css: out, files: n };
}

function main() {
  fs.mkdirSync(FONT_DIR, { recursive: true });
  const tmp = path.join(REPO, '.build-tmp');
  fs.mkdirSync(tmp, { recursive: true });

  const icons = collectIcons();
  const chunks = [css => css];

  let combined = '';

  for (const fam of FAMILIES) {
    const cssPath = path.join(tmp, `${fam.slug}.css`);
    curl(fam.url, cssPath);
    let css = fs.readFileSync(cssPath, 'utf8');

    // Download every referenced woff2 and point the @font-face at it.
    const urls = [...new Set([...css.matchAll(/url\((https:\/\/[^)]+)\)/g)].map((m) => m[1]))];
    for (const url of urls) {
      const file = `${fam.slug}-${path.basename(new URL(url).pathname)}`;
      curl(url, path.join(FONT_DIR, file));
    }
    css = css.replace(/url\((https:\/\/[^)]+)\)/g,
      (_m, url) => `url(fonts/${fam.slug}-${path.basename(new URL(url).pathname)})`);
    combined += `\n/* ${fam.name} */\n${css}`;
  }

  // Material Symbols, subset to the icons in use.
  {
    const fam = { name: 'Material Symbols Outlined', slug: 'material-symbols' };
    const names = icons.join(',');
    const cssPath = path.join(tmp, 'material-symbols.css');
    curl(`https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0,0&icon_names=${encodeURIComponent(names)}&display=swap`, cssPath);
    let css = fs.readFileSync(cssPath, 'utf8');
    const urls = [...new Set([...css.matchAll(/url\((https:\/\/[^)]+)\)/g)].map((m) => m[1]))];
    for (const url of urls) {
      const file = `${fam.slug}-${path.basename(new URL(url).pathname)}`;
      curl(url, path.join(FONT_DIR, file));
    }
    css = css.replace(/url\((https:\/\/[^)]+)\)/g,
      (_m, url) => `url(fonts/${fam.slug}-${path.basename(new URL(url).pathname)})`);
    combined += `\n/* ${fam.name} — ${icons.length} icons */\n${css}`;
  }

  fs.writeFileSync(path.join(WEB, 'fonts.css'),
    '/* Vendored webfonts. Generated by desktop/fetch-fonts.js — do not edit.\n' +
    ` * Sourced from Google Fonts at build time; ${icons.length} Material Symbols\n` +
    ' * glyphs only. Keeping these local is what lets the app render offline. */\n' +
    combined);

  const files = fs.readdirSync(FONT_DIR);
  const bytes = files.reduce((a, f) => a + fs.statSync(path.join(FONT_DIR, f)).size, 0);
  process.stdout.write(`icons subsetted: ${icons.length}\n`);
  process.stdout.write(`font files: ${files.length}  total ${(bytes / 1024).toFixed(0)} kB\n`);
}

main();